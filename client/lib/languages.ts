export function getLanguageById(id: string): SupportedLanguage {
  const found = SUPPORTED_LANGUAGES.find((lang) => lang.id.toLowerCase() === id.toLowerCase());
  return found || SUPPORTED_LANGUAGES[0];
}

export function formatLanguageLabel(id: string): string {
  const lang = getLanguageById(id);
  return `${lang.flag} ${lang.name} (${lang.nativeName})`;
}
